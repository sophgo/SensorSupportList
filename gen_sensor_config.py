#!/usr/bin/env python3
# Generate Kconfig.sensors (one bool per driver directory). Build-time
# artifact, not committed.

import os

SCRIPT_DIR = os.path.normpath(os.path.dirname(__file__))
KCONFIG_PATH = os.path.join(SCRIPT_DIR, "Kconfig.sensors")

# Non-driver directories in the repo root.
EXCLUDE_DIRS = {
    "CViTEK_Sensor_Support_List",  # docs
    "sensor_cfg",                  # shared lookup core (not a driver)
    "sensor_i2c",                  # shared i2c backends
    "sensor_list",                 # repo sensor list metadata (json)
    "rtt",                         # RT-Thread glue
    ".git",
}

KCONFIG_TMPL = """\
#
# Automatically generated by gen_sensor_config.py; DO NOT EDIT.
#

menu "Sensor settings"

{0}
endmenu
"""

KCONFIG_SENSOR_TMPL = """\
config SENSOR_{0}
    bool "sensor {1}"
    default n
    help
      Compile the {1} driver into the firmware.
"""


def get_sensor_dirs():
    sensor_dirs = []
    for entry in sorted(os.listdir(SCRIPT_DIR)):
        path = os.path.join(SCRIPT_DIR, entry)
        if not os.path.isdir(path) or entry in EXCLUDE_DIRS:
            continue
        if not any(f.endswith(".c") for f in os.listdir(path)):
            continue
        sensor_dirs.append(entry)
    return sensor_dirs


def gen_kconfig(sensor_dirs):
    body = "".join(
        KCONFIG_SENSOR_TMPL.format(d.upper(), d) for d in sensor_dirs)
    return KCONFIG_TMPL.format(body)


def regenerate():
    kconfig = gen_kconfig(get_sensor_dirs())
    if not os.path.exists(KCONFIG_PATH) or \
            open(KCONFIG_PATH).read() != kconfig:
        with open(KCONFIG_PATH, "w") as fp:
            fp.write(kconfig)
        print("gen_sensor_config: wrote %s (%d sensors)"
              % (KCONFIG_PATH, len(get_sensor_dirs())))


if __name__ == "__main__":
    regenerate()
