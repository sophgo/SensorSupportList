#define OS08C10_CHIP_ID_ADDR_H	0x300a
#define OS08C10_CHIP_ID_ADDR_M	0x300b
#define OS08C10_CHIP_ID_ADDR_L	0x300c
#define OS08C10_CHIP_ID_H		0x53
#define OS08C10_CHIP_ID_M		0x08
#define OS08C10_CHIP_ID_L		0x43

int os08c10_probe(VI_PIPE ViPipe)
{
	int nVal;
	int nVal2;
	int nVal3;

	usleep(50);
	if (os08c10_i2c_init(ViPipe) != CVI_SUCCESS)
		return CVI_FAILURE;

	nVal  = os08c10_read_register(ViPipe, OS08C10_CHIP_ID_ADDR_H);
	nVal2 = os08c10_read_register(ViPipe, OS08C10_CHIP_ID_ADDR_M);
	nVal3 = os08c10_read_register(ViPipe, OS08C10_CHIP_ID_ADDR_L);
	if (nVal < 0 || nVal2 < 0 || nVal3 < 0) {
		CVI_TRACE_SNS(CVI_DBG_ERR, "read sensor id error.\n");
		return nVal;
	}

	if ((nVal & 0xFF) != OS08C10_CHIP_ID_H ||
		(nVal2 & 0xFF) != OS08C10_CHIP_ID_M ||
		(nVal3 & 0xFF) != OS08C10_CHIP_ID_L) {
		CVI_TRACE_SNS(CVI_DBG_ERR, "Sensor ID Mismatch! Use the wrong sensor??\n");
		return CVI_FAILURE;
	}

	return CVI_SUCCESS;
}

void os08c10_default_reg_init(VI_PIPE ViPipe)
{
	CVI_U32 i;

	for (i = 0; i < g_pastOs08c10[ViPipe]->astSyncInfo[0].snsCfg.u32RegNum; i++) {
		os08c10_write_register(ViPipe,
				g_pastOs08c10[ViPipe]->astSyncInfo[0].snsCfg.astI2cData[i].u32RegAddr,
				g_pastOs08c10[ViPipe]->astSyncInfo[0].snsCfg.astI2cData[i].u32Data);
	}
}

void os08c10_init(VI_PIPE ViPipe)
{
	CVI_U8 u8ImgMode;

	u8ImgMode = g_pastOs08c10[ViPipe]->u8ImgMode;

	os08c10_i2c_init(ViPipe);

	if (u8ImgMode == OS08C10_MODE_1280X720P120_WDR)
		os08c10_wdr_720p120_2to1_init(ViPipe);
	else
		os08c10_wdr_1080p60_2to1_init(ViPipe);

	g_pastOs08c10[ViPipe]->bInit = CVI_TRUE;
}

void os08c10_exit(VI_PIPE ViPipe)
{
	os08c10_i2c_exit(ViPipe);
}

